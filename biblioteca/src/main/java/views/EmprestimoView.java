    public void carregarTabela() {
        DefaultTableModel modelo = (DefaultTableModel) tabelaEmprestimos.getModel();
        modelo.setRowCount(0);
        for (Emprestimo e : emprestimoController.listarEmprestimos()) {
            String status = e.isDevolvido() ? "Devolvido" : (e.calcularMulta() > 0 ? "Atrasado" : "Ativo");
            modelo.addRow(new Object[] {
                    e.getLivro().getIsbn(),
                    e.getMembro().getCpf(),
                    e.getDataEmprestimo(),
                    e.getDataDevolucaoPrevista(),
                    e.getDataDevolucaoReal() != null ? e.getDataDevolucaoReal() : "",
                    status
            });
        }
    }

