    private void btnNovoActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnNovoActionPerformed
        JDialog dialog = new JDialog();
        dialog.setTitle("Novo Empréstimo");
        dialog.setSize(400, 250);
        dialog.setModal(true);
        dialog.setLocationRelativeTo(this);

        JPanel painel = new JPanel(new GridLayout(3, 2, 10, 10));
        painel.setBorder(BorderFactory.createEmptyBorder(20, 20, 20, 20));

        JTextField fIsbn = new JTextField();
        JTextField fCpf = new JTextField();

        painel.add(new JLabel("ISBN do Livro:"));
        painel.add(fIsbn);
        painel.add(new JLabel("CPF do Membro:"));
        painel.add(fCpf);

        JButton btnSalvar = new JButton("Salvar");
        btnSalvar.setBackground(new java.awt.Color(67, 97, 238));
        btnSalvar.setForeground(java.awt.Color.WHITE);
        btnSalvar.setBorderPainted(false);

        btnSalvar.addActionListener(e -> {
            String isbn = fIsbn.getText().trim();
            String cpf = fCpf.getText().trim();
            if (isbn.isEmpty() || cpf.isEmpty()) {
                JOptionPane.showMessageDialog(dialog, "Preencha ISBN e CPF.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }

            Livro livro = livroController.buscarPorIsbn(isbn);
            Membro membro = membroController.buscarPorCpf(cpf);
            if (livro == null) {
                JOptionPane.showMessageDialog(dialog, "Livro não encontrado.", "Erro", JOptionPane.ERROR_MESSAGE);
                return;
            }
            if (membro == null) {
                JOptionPane.showMessageDialog(dialog, "Membro não encontrado.", "Erro", JOptionPane.ERROR_MESSAGE);
                return;
            }

            boolean sucesso = emprestimoController.realizarEmprestimo(usuarioLogado, livro, membro);
            if (sucesso) {
                carregarTabela();
                JOptionPane.showMessageDialog(dialog, "Empréstimo realizado com sucesso!", "Sucesso",
                        JOptionPane.INFORMATION_MESSAGE);
                dialog.dispose();
            } else {
                JOptionPane.showMessageDialog(dialog,
                        "Falha ao realizar empréstimo. Verifique se o membro não está suspenso, se já possui o livro ativo ou se há disponibilidade.",
                        "Erro", JOptionPane.ERROR_MESSAGE);
            }
        });

        painel.add(new JLabel());
        painel.add(btnSalvar);
        dialog.add(painel);
        dialog.setVisible(true);
    }// GEN-LAST:event_btnNovoActionPerformed

    private void btnDevolverActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnDevolverActionPerformed
        int row = tabelaEmprestimos.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Selecione um empréstimo.");
            return;
        }
        DefaultTableModel modelo = (DefaultTableModel) tabelaEmprestimos.getModel();
        String isbn = modelo.getValueAt(row, 0).toString();
        String cpf = modelo.getValueAt(row, 1).toString();
        String dataStr = modelo.getValueAt(row, 2).toString();
        LocalDate dataEmprestimo = LocalDate.parse(dataStr);
        Livro livro = livroController.buscarPorIsbn(isbn);
        Membro membro = membroController.buscarPorCpf(cpf);
        if (livro == null || membro == null) {
            JOptionPane.showMessageDialog(this, "Dados inconsistentes.");
            return;
        }
        boolean sucesso = emprestimoController.registrarDevolucao(usuarioLogado, livro, membro, dataEmprestimo);
        if (sucesso) {
            carregarTabela();
            JOptionPane.showMessageDialog(this, "Devolução registrada!");
        }
    }// GEN-LAST:event_btnDevolverActionPerformed

