    private void filtrarPorMembro() {
        String cpf = campoFiltroMembro.getText().trim();
        if (cpf.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digite um CPF.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        Membro membro = membroController.buscarPorCpf(cpf);
        if (membro == null) {
            JOptionPane.showMessageDialog(this, "Membro não encontrado.", "Erro", JOptionPane.ERROR_MESSAGE);
            return;
        }
        DefaultTableModel modelo = (DefaultTableModel) tabelaEmprestimos.getModel();
        modelo.setRowCount(0);
        
        for (Emprestimo e : emprestimoController.listarEmprestimosAtivosPorMembro(membro)) {
            modelo.addRow(new Object[] {
                    e.getLivro().getIsbn(),
                    e.getMembro().getCpf(),
                    e.getDataEmprestimo(),
                    e.getDataDevolucaoPrevista(),
                    e.getDataDevolucaoReal() != null ? e.getDataDevolucaoReal() : "",
                    e.isDevolvido() ? "Devolvido" : (e.calcularMulta() > 0 ? "Atrasado" : "Ativo")
            });
        }

        for (Emprestimo e : emprestimoController.listarEmprestimosAtrasadosPorMembro(membro)) {
            modelo.addRow(new Object[] {
                    e.getLivro().getIsbn(),
                    e.getMembro().getCpf(),
                    e.getDataEmprestimo(),
                    e.getDataDevolucaoPrevista(),
                    e.getDataDevolucaoReal() != null ? e.getDataDevolucaoReal() : "",
                    e.isDevolvido() ? "Devolvido" : (e.calcularMulta() > 0 ? "Atrasado" : "Ativo")
            });
        }
    }

