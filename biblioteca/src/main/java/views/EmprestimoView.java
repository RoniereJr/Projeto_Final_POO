    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {
        int row = tabelaEmprestimos.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Selecione um empréstimo para editar.", "Aviso",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        DefaultTableModel modelo = (DefaultTableModel) tabelaEmprestimos.getModel();
        String isbn = modelo.getValueAt(row, 0).toString();
        String cpf = modelo.getValueAt(row, 1).toString();
        String dataStr = modelo.getValueAt(row, 2).toString();
        LocalDate dataEmprestimo = LocalDate.parse(dataStr);
        LocalDate dataPrevista = LocalDate.parse(modelo.getValueAt(row, 3).toString());
        String dataRealStr = modelo.getValueAt(row, 4).toString();
        LocalDate dataReal = dataRealStr.isEmpty() ? null : LocalDate.parse(dataRealStr);
        boolean devolvido = "Devolvido".equals(modelo.getValueAt(row, 5));

        Emprestimo alvo = null;
        for (Emprestimo e : emprestimoController.listarEmprestimos()) {
            if (e.getLivro().getIsbn().equals(isbn) && e.getMembro().getCpf().equals(cpf)
                    && e.getDataEmprestimo().equals(dataEmprestimo)) {
                alvo = e;
                break;
            }
        }
        if (alvo == null) {
            JOptionPane.showMessageDialog(this, "Empréstimo não encontrado.", "Erro", JOptionPane.ERROR_MESSAGE);
            return;
        }

        JDialog dialog = new JDialog();
        dialog.setTitle("Editar Empréstimo");
        dialog.setSize(400, 300);
        dialog.setModal(true);
        dialog.setLocationRelativeTo(this);

        JPanel painel = new JPanel(new GridLayout(5, 2, 10, 10));
        painel.setBorder(BorderFactory.createEmptyBorder(20, 20, 20, 20));

        JTextField fDataEmp = new JTextField(dataEmprestimo.toString());
        JTextField fDataPrev = new JTextField(dataPrevista.toString());
        JTextField fDataReal = new JTextField(dataReal != null ? dataReal.toString() : "");
        JCheckBox cbDevolvido = new JCheckBox("Devolvido", devolvido);

        painel.add(new JLabel("Data Empréstimo:"));
        painel.add(fDataEmp);
        painel.add(new JLabel("Prev. Devolução:"));
        painel.add(fDataPrev);
        painel.add(new JLabel("Data Real:"));
        painel.add(fDataReal);
        painel.add(new JLabel("Devolvido:"));
        painel.add(cbDevolvido);

        JButton btnSalvar = new JButton("Salvar");
        final Emprestimo emprestimoAlvo = alvo;
        btnSalvar.addActionListener(e -> {
            try {
                LocalDate novaDataEmp = LocalDate.parse(fDataEmp.getText().trim());
                LocalDate novaDataPrev = LocalDate.parse(fDataPrev.getText().trim());
                LocalDate novaDataReal = fDataReal.getText().trim().isEmpty() ? null
                        : LocalDate.parse(fDataReal.getText().trim());
                boolean novoDevolvido = cbDevolvido.isSelected();
                boolean sucesso = emprestimoController.editarEmprestimo(usuarioLogado, emprestimoAlvo, novaDataEmp,
                        novaDataPrev,
                        novaDataReal, novoDevolvido);
                if (sucesso) {
                    carregarTabela();
                    JOptionPane.showMessageDialog(dialog, "Empréstimo editado!", "Sucesso",
                            JOptionPane.INFORMATION_MESSAGE);
                    dialog.dispose();
                }
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(dialog, "Erro ao editar: " + ex.getMessage(), "Erro",
                        JOptionPane.ERROR_MESSAGE);
            }
        });

        painel.add(new JLabel());
        painel.add(btnSalvar);
        dialog.add(painel);
        dialog.setVisible(true);
    }

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {
        int row = tabelaEmprestimos.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Selecione um empréstimo.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        DefaultTableModel modelo = (DefaultTableModel) tabelaEmprestimos.getModel();
        String isbn = modelo.getValueAt(row, 0).toString();
        String cpf = modelo.getValueAt(row, 1).toString();
        String dataStr = modelo.getValueAt(row, 2).toString();
        LocalDate dataEmprestimo = LocalDate.parse(dataStr);

        Emprestimo alvo = null;
        for (Emprestimo e : emprestimoController.listarEmprestimos()) {
            if (e.getLivro().getIsbn().equals(isbn) && e.getMembro().getCpf().equals(cpf)
                    && e.getDataEmprestimo().equals(dataEmprestimo)) {
                alvo = e;
                break;
            }
        }
        if (alvo == null) {
            JOptionPane.showMessageDialog(this, "Empréstimo não encontrado.", "Erro", JOptionPane.ERROR_MESSAGE);
            return;
        }
        final Emprestimo emprestimoAlvo = alvo;
        int confirm = JOptionPane.showConfirmDialog(this, "Excluir este empréstimo?", "Confirmar",
                JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            boolean sucesso = emprestimoController.excluirEmprestimo(usuarioLogado, emprestimoAlvo);
            if (sucesso) {
                carregarTabela();
                JOptionPane.showMessageDialog(this, "Empréstimo excluído!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Falha ao excluir.", "Erro", JOptionPane.ERROR_MESSAGE);
            }
        }
    }

